# shellcheck shell=bash
# The additive merge of the root files that parallel tickets all add to (#716, part 1 of #676): serve.sharedPaths lists
# them, and each kind of file has a mechanical merge that fails when the change is not purely additive. Definitions only;
# serve's conflict path calls them in part 2.

# The root files of serve.sharedPaths, one per line (none when the key is not set).
additive_shared_paths() {
  config_effective 2>/dev/null | jq -r '(.serve.sharedPaths // [])[] | strings' 2>/dev/null || true
}

# The kind of a file, from its name: json (package.json), markdown, lockfile; nothing for any other file.
additive_kind() {
  case ${1##*/} in
    package.json) echo json ;;
    pnpm-lock.yaml | package-lock.json | yarn.lock) echo lockfile ;;
    *.md) echo markdown ;;
  esac
}

# additive_merge <name> <base> <ours> <theirs>: prints the merge of two versions of a package.json or a Markdown file
# over their common base, or fails (1, the reason on stderr) when the two sides do not only add. <name> picks the kind.
additive_merge() {
  case $(additive_kind "$1") in
    json) additive_merge_json "$1" "$2" "$3" "$4" ;;
    markdown) additive_merge_markdown "$1" "$2" "$3" "$4" ;;
    lockfile) echo "additive: $1 is a lockfile: it is regenerated, never merged" >&2; return 1 ;;
    *) echo "additive: no additive merge for $1" >&2; return 1 ;;
  esac
}

# package.json: the union of the keys of scripts, dependencies, devDependencies and peerDependencies (the same key with
# two different values, or a key one side removed, fails and names it); any other field is taken from the side that
# changed it, and fails when both did differently.
# shellcheck disable=SC2016 # a jq program, not shell
ADDITIVE_JSON='
def maps: ["scripts", "dependencies", "devDependencies", "peerDependencies"];
def slot($o; $k): if $o | has($k) then [$o[$k]] else [] end;
$b[0] as $b | $o[0] as $o | $t[0] as $t
| (($o | keys_unsorted) + (($t | keys_unsorted) - ($o | keys_unsorted))
   + (($b | keys_unsorted) - ($o | keys_unsorted) - ($t | keys_unsorted))) as $order
| reduce $order[] as $k ({};
    if (maps | index($k)) != null then
      ($b[$k] // {}) as $bm | ($o[$k] // {}) as $om | ($t[$k] // {}) as $tm
      | ([$bm | keys[] | . as $x | select(($om | has($x) | not) or ($tm | has($x) | not))] | first) as $gone
      | (if $gone != null then error("\($k).\($gone): removed by one side, not an addition") else . end)
      | ([$om | keys[] | . as $x | select($tm | has($x)) | select($om[$x] != $tm[$x])] | first) as $clash
      | (if $clash != null then error("\($k).\($clash): ours \($om[$clash] | tojson), theirs \($tm[$clash] | tojson)") else . end)
      | if ($o | has($k)) or ($t | has($k)) then .[$k] = ($om + ($tm | with_entries(select(.key as $x | $om | has($x) | not)))) else . end
    else
      slot($o; $k) as $ov | slot($t; $k) as $tv | slot($b; $k) as $bv
      | (if $ov == $tv then $ov elif $ov == $bv then $tv elif $tv == $bv then $ov
         else error("\($k): changed differently by both sides") end) as $pick
      | if $pick == [] then . else .[$k] = $pick[0] end
    end)';

additive_merge_json() { # name base ours theirs
  local name=$1 f out
  for f in "$2" "$3" "$4"; do
    jq -e 'type == "object"' "$f" >/dev/null 2>&1 || { echo "additive: $name: $f is not a JSON object" >&2; return 1; }
  done
  out=$(jq -n --slurpfile b "$2" --slurpfile o "$3" --slurpfile t "$4" "$ADDITIVE_JSON" 2>&1) || {
    echo "additive: $name: $(sed -n '1s/^jq: error (at [^)]*): //p' <<<"$out")" >&2
    return 1
  }
  printf '%s\n' "$out"
}

# Markdown: both sides appended after the common text, ours first, provided that text is untouched in both (an edited
# line fails). The same text appended by both sides is kept once.
additive_merge_markdown() { # name base ours theirs
  local name=$1 n f
  n=$(wc -c <"$2")
  for f in "$3" "$4"; do
    [ "$(wc -c <"$f")" -ge "$n" ] && cmp -s -n "$n" "$2" "$f" ||
      { echo "additive: $name: ${f##*/} does not keep the common text as it was: not an addition" >&2; return 1; }
  done
  cat "$2"
  tail -c +$((n + 1)) "$3"
  if ! cmp -s <(tail -c +$((n + 1)) "$3") <(tail -c +$((n + 1)) "$4"); then
    tail -c +$((n + 1)) "$4"
  fi
}

# The command that regenerates the lockfile $1 without merging it.
additive_lockfile_command() {
  case ${1##*/} in
    pnpm-lock.yaml) echo "pnpm install --lockfile-only" ;;
    package-lock.json) echo "npm install --package-lock-only" ;;
    yarn.lock) echo "yarn install" ;;
  esac
}

# additive_resolve <root> <path> <base> <ours> <theirs>: resolves the file <path> of the checkout <root> that conflicted
# and stages it. package.json and Markdown are merged (additive_merge); a lockfile starts again from ours and is
# regenerated by the install command of its package manager, then staged.
additive_resolve() {
  local root=$1 path=$2 kind cmd tmp
  kind=$(additive_kind "$path")
  case $kind in
    json | markdown)
      tmp=$(mktemp) || return 1
      additive_merge "$path" "$3" "$4" "$5" >"$tmp" || { rm -f "$tmp"; return 1; }
      cat "$tmp" >"$root/$path"
      rm -f "$tmp"
      ;;
    lockfile)
      cmd=$(additive_lockfile_command "$path")
      cp "$4" "$root/$path"
      (cd "$root" && net_bound 900 bash -c "$cmd" </dev/null >&2) ||
        { echo "additive: $path: could not regenerate it with: $cmd" >&2; return 1; }
      ;;
    *) echo "additive: no additive merge for $path" >&2; return 1 ;;
  esac
  git -C "$root" add -- "$path"
}
