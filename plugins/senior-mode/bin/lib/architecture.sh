#!/usr/bin/env bash
# `architecture`: the generated map of docs/architecture.md (#347, spec 325 §6.4). Definitions only; sourced by the entry.

ARCH_OPEN_RE='^<!-- senior-mode:architecture sha=[0-9a-f]+ -->$'
ARCH_CLOSE='<!-- /senior-mode:architecture -->'

# The directories of the tree $1 down to depth 2, one per line with a trailing slash, sorted; hidden ones left out.
arch_dirs() {
  git -C "$1" -c core.quotePath=false ls-files -co --exclude-standard |
    awk -F/ 'NF > 1 && $1 !~ /^\./ { print $1 "/"; if (NF > 2 && $2 !~ /^\./) print $1 "/" $2 "/" }' | LC_ALL=C sort -u
}

# The accepted specs of $1 as `<directory prefix of a paths glob><TAB><title>` rows, in file name order.
arch_spec_rows() {
  local f fm title paths
  for f in "$1"/docs/specs/*.md; do
    [ -f "$f" ] || continue
    fm=$(awk 'NR == 1 && $0 != "---" { exit } NR > 1 && $0 == "---" { exit } NR > 1 { print }' "$f")
    grep -qE '^status:[[:space:]]*"?accepted' <<<"$fm" || continue
    title=$(sed -n 's/^title:[[:space:]]*//p' <<<"$fm" | head -n 1 | tr -d '\r' | sed -E 's/^"(.*)"$/\1/')
    paths=$(sed -n 's/^paths:[[:space:]]*//p' <<<"$fm" | head -n 1 | tr -d '\r')
    [ -n "$title" ] || continue
    jq -r --arg t "$title" 'if type == "array" then .[] | select(type == "string") | sub("/?[^/]*[*?\\[].*$"; "") | select(. != "") | [., $t] | @tsv else empty end' \
      <<<"$paths" 2>/dev/null || true
  done
}

# What the directory $2 (with its trailing slash) of the tree $1 is for: the title of the spec whose paths govern it
# (the longest prefix wins, the first spec of the rows $3 on a tie), else the first line of its README.md. Nothing else.
arch_purpose() {
  local root=$1 dir=${2%/} rows=$3 title line
  title=$(awk -F'\t' -v d="$dir" '($1 == d || index(d, $1 "/") == 1) && length($1) > best { best = length($1); t = $2 } END { print t }' <<<"$rows")
  if [ -n "$title" ]; then
    printf '%s\n' "$title"
    return 0
  fi
  [ -f "$root/$dir/README.md" ] || return 0
  line=$(grep -m1 -E '[^[:space:]]' "$root/$dir/README.md" | tr -d '\r' | sed -E 's/^[#[:space:]]+//; s/[[:space:]]+$//' | cut -c1-100) || true
  printf '%s\n' "$line"
}

# The rules of `architecture.rules`, one `- \`id\`: why` line each.
arch_rules() {
  local rules
  rules=$(config_get architecture.rules 2>/dev/null) || rules='[]'
  jq -r 'if type == "array" then .[] | select(type == "object" and (.id | type) == "string") | "- `\(.id)`" + (if (.why | type) == "string" then ": \(.why)" else "" end) else empty end' \
    <<<"$rules" 2>/dev/null || true
}

# The ADRs of $1 as `- [<id>](adr/<file>): <title>` lines, in file name order.
arch_adrs() {
  local f fm id title base
  for f in "$1"/docs/adr/*.md; do
    [ -f "$f" ] || continue
    base=$(basename "$f")
    [ "$base" != README.md ] || continue
    fm=$(awk 'NR == 1 && $0 != "---" { exit } NR > 1 && $0 == "---" { exit } NR > 1 { print }' "$f")
    id=$(sed -n 's/^id:[[:space:]]*//p' <<<"$fm" | head -n 1 | tr -d "\r\"'")
    title=$(sed -n 's/^title:[[:space:]]*//p' <<<"$fm" | head -n 1 | tr -d '\r' | sed -E 's/^"(.*)"$/\1/')
    [ -n "$id" ] || id=${base%%-*}
    [ -n "$title" ] || title=$(sed -n 's/^# //p' "$f" | head -n 1 | tr -d '\r')
    [ -n "$title" ] || title=${base%.md}
    printf -- '- [%s](adr/%s): %s\n' "$id" "$base" "$title"
  done
}

# The block of the repository $1: markers, the hash of its tree, rules and ADR list, then the map.
arch_block() {
  local root=$1 dirs rows rules adrs notes sha d purpose lines="" n=0
  dirs=$(arch_dirs "$root")
  rows=$(arch_spec_rows "$root")
  rules=$(arch_rules)
  adrs=$(arch_adrs "$root")
  sha=$(printf '%s\n--\n%s\n--\n%s\n' "$dirs" "$rules" "$adrs" | sha256sum | cut -c1-12)
  while IFS= read -r d; do
    [ -n "$d" ] || continue
    purpose=$(arch_purpose "$root" "$d" "$rows")
    lines+="- \`$d\`${purpose:+: $purpose}"$'\n'
  done <<<"$dirs"
  if [ -d "$root/docs/knowledge" ]; then
    n=$(find "$root/docs/knowledge" -maxdepth 1 -type f -name '*.md' | grep -c '') || n=0
  fi
  notes=$n
  printf '<!-- senior-mode:architecture sha=%s -->\n' "$sha"
  printf '## Map\n\nGenerated by `senior-mode architecture --write`: edit outside this block.\n\n### Directories\n\n%s\n' "${lines:-None.$'\n'}"
  printf '### Architecture rules\n\n%s\n\n' "${rules:-None configured.}"
  printf '### Decisions\n\n%s\n\n' "${adrs:-None.}"
  printf '### Knowledge\n\nKnowledge notes: %s\n' "$notes"
  printf '%s\n' "$ARCH_CLOSE"
}

# `senior-mode architecture [--write|--check]`: prints the block; --write puts it in docs/architecture.md (the block
# between the markers replaced, the rest untouched, appended when the file has none); --check warns, never fails, when
# the hash recorded in the file differs from the current one, and says nothing without the file or its block.
architecture_cmd() {
  local mode=${1:-} root file block tmp recorded current
  case $mode in '' | --write | --check) ;; *) usage ;; esac
  root=$(git rev-parse --show-toplevel) || die "not inside a git repository"
  file=$root/docs/architecture.md
  if [ "$mode" = --check ]; then
    [ -f "$file" ] || return 0
    recorded=$(sed -nE 's/^<!-- senior-mode:architecture sha=([0-9a-f]+) -->$/\1/p' "$file" | head -n 1)
    [ -n "$recorded" ] || return 0
    current=$(arch_block "$root" | sed -nE 's/^<!-- senior-mode:architecture sha=([0-9a-f]+) -->$/\1/p')
    [ "$recorded" = "$current" ] ||
      echo "warning: architecture.md out of date: its tree, rules or ADR list changed since the block was written (senior-mode architecture --write)"
    return 0
  fi
  block=$(arch_block "$root")
  if [ -z "$mode" ]; then
    printf '%s\n' "$block"
    return 0
  fi
  [ -f "$file" ] || die "no docs/architecture.md to write into: create it first (the docs skill, or /senior-mode:setup)"
  tmp=$(mktemp "$file.XXXXXX")
  if grep -qE "$ARCH_OPEN_RE" "$file"; then
    grep -qxF "$ARCH_CLOSE" "$file" || { rm -f "$tmp"; die "docs/architecture.md: the block has no closing marker $ARCH_CLOSE"; }
    ARCH_BLOCK=$block ARCH_CLOSE=$ARCH_CLOSE awk '
      /^<!-- senior-mode:architecture sha=[0-9a-f]+ -->$/ && !done { print ENVIRON["ARCH_BLOCK"]; skip = 1; done = 1; next }
      skip { if ($0 == ENVIRON["ARCH_CLOSE"]) skip = 0; next }
      { print }' "$file" >"$tmp"
  else
    { cat "$file"; [ ! -s "$file" ] || [ -z "$(tail -c 1 "$file")" ] || echo; [ ! -s "$file" ] || echo; printf '%s\n' "$block"; } >"$tmp"
  fi
  if cmp -s "$tmp" "$file"; then
    rm -f "$tmp"
  else
    chmod --reference="$file" "$tmp"
    mv "$tmp" "$file"
  fi
  echo "docs/architecture.md: map written"
}
